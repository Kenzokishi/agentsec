import type { ScanResult } from "../core/types.js";

const OWASP_NAME: Record<string, string> = {
  LLM01: "Prompt Injection",
  LLM02: "Sensitive Information Disclosure",
  LLM06: "Excessive Agency",
  LLM07: "System Prompt Leakage",
  LLM08: "Vector & Embedding Weaknesses",
};

const STATUS_ICON = { vulnerable: "🔴", safe: "🟢", error: "🟡" } as const;

/** Renders a scan result as a Markdown report suitable for a PR comment or CI artifact. */
export function renderMarkdown(result: ScanResult): string {
  const out: string[] = [];
  out.push(`# agentsec report — ${result.target}`);
  out.push("");
  out.push(`**Score: ${result.score}/100** · ${result.counts.vulnerable} vulnerable · ${result.counts.safe} safe · ${result.counts.error} errors`);
  out.push("");
  out.push(`Scanned ${result.startedAt} · ${result.findings.length} probes · mapped to the [OWASP Top 10 for LLM Applications](https://genai.owasp.org/llm-top-10/).`);
  out.push("");
  out.push("| Status | Finding | OWASP | Severity |");
  out.push("| --- | --- | --- | --- |");
  for (const f of result.findings) {
    out.push(
      `| ${STATUS_ICON[f.status]} ${f.status} | ${f.title} | ${f.owasp} ${OWASP_NAME[f.owasp] ?? ""} | ${f.severity} |`,
    );
  }
  out.push("");

  const vulns = result.findings.filter((f) => f.status === "vulnerable");
  if (vulns.length > 0) {
    out.push("## Vulnerabilities");
    out.push("");
    for (const f of vulns) {
      out.push(`### ${f.title} — \`${f.owasp}\` (${f.severity})`);
      out.push("");
      out.push(`**Attack sent:** \`${f.attack}\``);
      out.push("");
      out.push(`**Evidence:** ${f.evidence}`);
      out.push("");
      out.push(`**Remediation:** ${f.remediation}`);
      out.push("");
    }
  }

  out.push("---");
  out.push("");
  out.push("_Generated by [agentsec](https://github.com/Kenzokishi/agentsec) — an open-source red-team scanner for LLM apps, agents and MCP servers._");
  out.push("");
  return out.join("\n");
}
